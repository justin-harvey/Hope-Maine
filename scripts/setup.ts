/**
 * One-time setup for a new town.
 *
 *   npm run setup
 *
 * Asks a short series of questions, then does everything that can be done
 * inside the repository: writes src/town.config.ts and .env, generates a
 * PAYLOAD_SECRET, seeds the first administrator, and prints a plain report of
 * what still needs provisioning outside the repo (the database, file storage,
 * and email). Provisioning those external services is a documented checklist
 * in SETUP.md, not something a script can do for you.
 *
 * Safe to re-run: it shows the current values as defaults and overwrites the
 * two files with your answers. It never touches src/data/ or the database
 * beyond the idempotent seed.
 */
import "dotenv/config";

import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import readline from "node:readline/promises";
import { stdin as input, stdout as output } from "node:process";

const ROOT = path.resolve(import.meta.dirname, "..");
const CONFIG_PATH = path.join(ROOT, "src", "town.config.ts");
const ENV_PATH = path.join(ROOT, ".env");

type Answers = {
  name: string;
  legalName: string;
  state: string;
  stateAbbr: string;
  incorporatedYear: number | null;
  tagline: string;
  timezone: string;
  siteUrl: string;
  firstAdminEmail: string;
  adminPassword: string;
  officeName: string;
  addressLine: string;
  cityStateZip: string;
  phone: string;
  fax: string;
  email: string;
  officeDays: string;
  officeTimes: string;
  legacySiteBaseUrl: string | null;
};

/** The full src/town.config.ts, rebuilt from the answers. */
function renderTownConfig(a: Answers): string {
  const townObject = {
    name: a.name,
    legalName: a.legalName,
    state: a.state,
    stateAbbr: a.stateAbbr,
    incorporatedYear: a.incorporatedYear,
    tagline: a.tagline,
    timezone: a.timezone,
    siteUrl: a.siteUrl,
    firstAdminEmail: a.firstAdminEmail,
    adminTitleSuffix: ` · ${a.legalName}`,
    contact: {
      officeName: a.officeName,
      addressLine: a.addressLine,
      cityStateZip: a.cityStateZip,
      phone: a.phone,
      fax: a.fax,
      email: a.email,
      officeHours: [{ days: a.officeDays, hours: a.officeTimes }],
    },
    hero: {
      alt: "Placeholder. Drop a photo into public/hero/ and update this alt text.",
      intro: `Welcome to the ${a.legalName}, ${a.state}. Edit this introduction in src/town.config.ts.`,
      credit: null,
    },
    documentCategories: [
      "Annual Town Reports",
      "Ordinances",
      "Policies",
      "Budgets & Financial Statements",
      "Tax Maps",
      "Permits, Forms & Applications",
      "Agendas & Minutes",
    ],
    boardSeedOrder: {
      "Select Board": 10,
      "Planning Board": 20,
      "Board of Appeals": 30,
      "Budget Committee": 40,
    },
    legacySiteBaseUrl: a.legacySiteBaseUrl,
  };

  const literal = JSON.stringify(townObject, null, 2);

  return `/**
 * The one file this town edits.
 *
 * Generated by \`npm run setup\`. Every town-specific fact the site shows lives
 * here and nowhere else; change a value and the whole site follows. Content
 * (news, rosters, documents, "How Do I" answers) is managed in the admin at
 * /admin, not here.
 */

export type OfficeHours = {
  /** e.g. "Tuesday, Wednesday & Friday" */
  days: string;
  /** e.g. "8:30 AM – 4:30 PM", or "Closed" */
  hours: string;
};

export type TownConfig = {
  /** The place name on its own: "Hope". Used in prose like "About Hope". */
  name: string;
  /** The legal municipal name: "Town of Hope". */
  legalName: string;
  /** "Maine" */
  state: string;
  /** "ME" */
  stateAbbr: string;
  /** Year of incorporation, shown under the masthead. Null to hide it. */
  incorporatedYear: number | null;
  /** One line under the name in some contexts. */
  tagline: string;
  /** IANA zone meeting times are entered and read in. Defaults to Eastern. */
  timezone: string;
  /** Canonical origin, e.g. "https://hope-maine.netlify.app". Env overrides. */
  siteUrl: string;
  /** The first admin account the seed creates. */
  firstAdminEmail: string;
  /** Appended to the browser tab title inside the admin panel. */
  adminTitleSuffix: string;
  contact: {
    /** "Hope Town Office" -- the name of the building/office. */
    officeName: string;
    /** Street line, e.g. "441 Camden Rd". */
    addressLine: string;
    /** "Hope, ME 04847". */
    cityStateZip: string;
    phone: string;
    fax: string;
    email: string;
    officeHours: OfficeHours[];
  };
  hero: {
    /** Alt text for the home-page hero image, if one is dropped in public/hero/. */
    alt: string;
    /** The single sentence of home-page intro copy beneath the hero. */
    intro: string;
    /** Photo credit when the hero is a stock image. Null if the town's own photo. */
    credit: { photographer: string; source: string } | null;
  };
  /** Categories a document can be filed under. First one is the default. */
  documentCategories: string[];
  /** Starting sort order for seeded boards (lower comes first). */
  boardSeedOrder: Record<string, number>;
  /** Base URL of the town's previous website, or null when there is none. */
  legacySiteBaseUrl: string | null;
};

export const town: TownConfig = ${literal};

/** "Town of Hope, Maine" -- the full display name used in titles and the masthead. */
export const townDisplayName = \`\${town.legalName}, \${town.state}\`;

/** "Hope, Maine" -- the shorter name. */
export const townShortName = \`\${town.name}, \${town.state}\`;

/**
 * Host of the legacy site (e.g. "hopemaine.org"), with any leading "www."
 * stripped, for the migration notices. Null when there is no prior site.
 */
export const legacySiteHost = town.legacySiteBaseUrl
  ? new URL(town.legacySiteBaseUrl).host.replace(/^www\\./, "")
  : null;
`;
}

/** The .env, preserving any DATABASE_URI/S3 values already set. */
function renderEnv(a: Answers, existing: Record<string, string>): string {
  const secret = existing.PAYLOAD_SECRET || randomBytes(32).toString("hex");
  const v = (k: string) => existing[k] ?? "";
  return `# Signs the login cookies for /admin. Generated by npm run setup.
# Changing it logs every editor out, which is what you want if it ever leaks.
PAYLOAD_SECRET=${secret}

# Deployed environments MUST point this at Postgres (Netlify/Vercel rebuild the
# filesystem on every deploy, so a SQLite file there loses everything written).
#   DATABASE_URI=postgresql://user:password@host/dbname
DATABASE_URI=${v("DATABASE_URI")}

# The site's own origin, used to build absolute URLs for uploaded files.
NEXT_PUBLIC_SITE_URL=${a.siteUrl}

# ── File storage (S3-compatible) ─────────────────────────────
# Without these, uploads write to a filesystem the host rebuilds on deploy and
# are lost. Supabase, Cloudflare R2, Backblaze B2, and AWS S3 all work.
S3_ENDPOINT=${v("S3_ENDPOINT")}
S3_REGION=${v("S3_REGION")}
S3_BUCKET=${v("S3_BUCKET")}
S3_ACCESS_KEY_ID=${v("S3_ACCESS_KEY_ID")}
S3_SECRET_ACCESS_KEY=${v("S3_SECRET_ACCESS_KEY")}

# ── Email (password reset) ───────────────────────────────────
# Without SMTP_HOST, password-reset emails are only logged to the server
# console. Set these to a real SMTP provider before launch. Any provider
# works (the town mailbox, Resend/SendGrid/Mailgun SMTP, etc.).
#   SMTP_PORT defaults to 587 (STARTTLS); use 465 for implicit TLS.
SMTP_HOST=${v("SMTP_HOST")}
SMTP_PORT=${v("SMTP_PORT")}
SMTP_USER=${v("SMTP_USER")}
SMTP_PASS=${v("SMTP_PASS")}
EMAIL_FROM=${v("EMAIL_FROM")}
EMAIL_FROM_NAME=${v("EMAIL_FROM_NAME")}
`;
}

/** Minimal KEY=VALUE parser for an existing .env, to preserve set values. */
function parseEnv(text: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

async function main() {
  // A line reader that works whether stdin is an interactive TTY or a pipe.
  // readline/promises' question() abandons a pending prompt the moment piped
  // input hits EOF, which silently cuts a scripted run short; buffering lines
  // ourselves and resolving defaults after close avoids that.
  const rl = readline.createInterface({ input, output });
  const queued: string[] = [];
  const waiting: ((line: string) => void)[] = [];
  let closed = false;
  rl.on("line", (l) => {
    const w = waiting.shift();
    if (w) w(l);
    else queued.push(l);
  });
  rl.on("close", () => {
    closed = true;
    while (waiting.length) waiting.shift()!("");
  });
  const nextLine = (): Promise<string> => {
    if (queued.length) return Promise.resolve(queued.shift()!);
    if (closed) return Promise.resolve("");
    return new Promise((resolve) => waiting.push(resolve));
  };
  const ask = async (q: string, def = ""): Promise<string> => {
    output.write(`${q}${def ? ` [${def}]` : ""}: `);
    const answer = (await nextLine()).trim();
    return answer || def;
  };

  console.log("\nSetting up a new town site. Press Enter to accept a default in [brackets].\n");

  const name = await ask("Town name (e.g. Hope)");
  if (!name) {
    console.error("A town name is required. Nothing was written.");
    rl.close();
    process.exitCode = 1;
    return;
  }
  const legalName = await ask("Legal name", `Town of ${name}`);
  const state = await ask("State", "Maine");
  const stateAbbr = await ask("State abbreviation", "ME");
  const yearRaw = await ask("Year incorporated (optional)");
  const incorporatedYear = yearRaw && /^\d{3,4}$/.test(yearRaw) ? Number(yearRaw) : null;
  const tagline = await ask("Short tagline (optional)", "");

  console.log("\nContact details for the town office:");
  const officeName = await ask("  Office name", `${name} Town Office`);
  const addressLine = await ask("  Street address", "1 Main Street");
  const cityStateZip = await ask("  City, State ZIP", `${name}, ${stateAbbr} `);
  const phone = await ask("  Phone", "");
  const fax = await ask("  Fax (optional)", "");
  const email = await ask("  Public email", "");
  const officeDays = await ask("  Office hours — days", "Monday – Friday");
  const officeTimes = await ask("  Office hours — times", "8:30 AM – 4:30 PM");

  console.log("");
  const timezone = await ask("Timezone (IANA)", "America/New_York");
  const siteUrl = await ask("Site URL", "http://localhost:3000");
  const firstAdminEmail = await ask("First administrator email", email || "admin@example.com");
  const adminPassword = await ask("First administrator password (optional)", "");
  const legacyRaw = await ask("Old website URL, if migrating (optional)", "");
  const legacySiteBaseUrl = legacyRaw ? legacyRaw.replace(/\/+$/, "") : null;

  const answers: Answers = {
    name, legalName, state, stateAbbr, incorporatedYear, tagline, timezone, siteUrl,
    firstAdminEmail, adminPassword, officeName, addressLine, cityStateZip, phone, fax,
    email, officeDays, officeTimes, legacySiteBaseUrl,
  };

  // ── Write the two files ──────────────────────────────────────
  writeFileSync(CONFIG_PATH, renderTownConfig(answers));
  console.log(`\nWrote ${path.relative(ROOT, CONFIG_PATH)}`);

  const existingEnv = existsSync(ENV_PATH) ? parseEnv(readFileSync(ENV_PATH, "utf8")) : {};
  const hadSecret = Boolean(existingEnv.PAYLOAD_SECRET);
  writeFileSync(ENV_PATH, renderEnv(answers, existingEnv));
  console.log(`Wrote ${path.relative(ROOT, ENV_PATH)}${hadSecret ? "" : " (generated a fresh PAYLOAD_SECRET)"}`);

  rl.close();

  // ── Seed the first administrator ─────────────────────────────
  console.log("\nSeeding the first administrator...");
  const seed = spawnSync("npm", ["run", "seed"], {
    cwd: ROOT,
    stdio: "inherit",
    env: { ...process.env, ...(adminPassword ? { SEED_ADMIN_PASSWORD: adminPassword } : {}) },
  });
  if (seed.status !== 0) {
    console.error("\nSeed failed. Fix the error above and re-run `npm run seed`.");
  }

  // ── Readiness report ─────────────────────────────────────────
  const env = parseEnv(readFileSync(ENV_PATH, "utf8"));
  const emailConfigured = Boolean(env.SMTP_HOST);
  const s3Vars = ["S3_ENDPOINT", "S3_REGION", "S3_BUCKET", "S3_ACCESS_KEY_ID", "S3_SECRET_ACCESS_KEY"];
  const s3Missing = s3Vars.filter((k) => !env[k]);

  console.log("\n────────────────────────────────────────────");
  console.log("Readiness — what still needs provisioning");
  console.log("────────────────────────────────────────────");
  const line = (ok: boolean, label: string, note: string) =>
    console.log(`  ${ok ? "ready " : "TODO  "} ${label}${ok ? "" : ` — ${note}`}`);

  line(Boolean(env.PAYLOAD_SECRET), "PAYLOAD_SECRET", "run setup again");
  line(
    Boolean(env.DATABASE_URI),
    "Database (Postgres)",
    "local SQLite works for now; set DATABASE_URI to a Postgres URL (Neon/Supabase) before deploying",
  );
  line(
    s3Missing.length === 0,
    "File storage (S3)",
    `uploads are not persisted across deploys; set ${s3Missing.join(", ")}`,
  );
  line(
    emailConfigured,
    "Email (password reset)",
    "set SMTP_HOST / SMTP_USER / SMTP_PASS so /admin can send reset emails; see SETUP.md",
  );

  if (answers.legacySiteBaseUrl) {
    console.log("\nAn old website was given. You can migrate its content with:");
    console.log(`  python3 tools/migrate/crawl.py ${answers.legacySiteBaseUrl} --out ./migration`);
    console.log("  python3 tools/migrate/extract.py --out ./migration");
    console.log("  python3 tools/migrate/fetch_assets.py --out ./migration --include-external");
    console.log("(needs: pip3 install requests beautifulsoup4 html2text — see tools/README.md)");
  }

  console.log("\nDone. Start the site with `npm run dev` and sign in at /admin.");
  if (!adminPassword) {
    console.log("The seed printed the default admin credentials above — change the password immediately.");
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
